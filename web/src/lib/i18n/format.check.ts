import assert from "node:assert/strict";
import { money, price, perShareValue, shares, pctDelta, weight, date, quarter, range } from "./format";

assert.equal(money(162_000_000, "zh"), "1.62亿美元");
assert.equal(money(162_000_000, "zh", "table"), "1.62亿");
assert.equal(money(963_518, "zh"), "96.4万美元");
assert.equal(money(162_000_000, "en"), "$162M");
assert.equal(money(963_518, "en"), "$964K");
assert.equal(money(999_999_999, "en"), "$1B");
assert.equal(money(99_999_999, "zh"), "1亿美元");
assert.equal(money(-162_000_000, "zh"), "−1.62亿美元");
assert.equal(money(-162_000_000, "en"), "−$162M");
assert.equal(money(0, "zh"), "0美元");
assert.equal(money(-0, "en"), "$0");
assert.equal(money(12.34, "en"), "$12.34");
assert.equal(money(NaN, "zh"), "—");
assert.equal(money(Infinity, "en"), "—");
assert.equal(price(2.88), "$2.88");
assert.equal(price(-2.88), "−$2.88");
assert.equal(perShareValue(12.34), "$12");
assert.equal(perShareValue(2.51), "$2.51");
assert.equal(shares(227_917_808, "zh"), "2.28亿");
assert.equal(shares(227_917_808, "en"), "227,917,808");
assert.equal(pctDelta(-0.123), "−12.3%");
assert.equal(pctDelta(-0.00001), "0%");
assert.equal(weight(0.00001), "<0.1%");
assert.equal(weight(0), "0.0%");
assert.equal(weight(null), "—");
assert.equal(date("2026-06-30", "zh"), "2026年6月30日");
assert.equal(date("2026-06-30", "zh", "table"), "2026-06-30");
assert.equal(date("2026-06-30", "en"), "Jun 30, 2026");
assert.equal(date("2026-06-30T23:00:00Z", "zh"), "2026年6月30日");
assert.equal(date("2026-02-30", "zh"), "2026-02-30");
assert.equal(date("2026-06-30Tgarbage", "zh"), "2026-06-30Tgarbage");
assert.equal(date("2026-06-30T25:00:00Z", "zh"), "2026-06-30T25:00:00Z");
assert.equal(quarter("2026-06-30Tgarbage", "zh"), "2026-06-30Tgarbage");
assert.equal(date("", "en"), "");
assert.equal(quarter("2026-06-30", "zh"), "2026Q2");
assert.equal(quarter("2026-06-30", "en"), "Q2 2026");
assert.equal(quarter("2026-06-30", "zh", "prose"), "2026年二季度");
assert.equal(quarter("2026-06-30", "en", "prose"), "the second quarter of 2026");
assert.equal(quarter("2026-13-31", "zh"), "2026-13-31");
assert.equal(quarter(null, "en"), "");
assert.equal(range(12.1, 12.4, perShareValue), "$12");
assert.equal(range(2.1, 3.2, price), "$2.10–$3.20");
console.log("i18n/format.check OK");
